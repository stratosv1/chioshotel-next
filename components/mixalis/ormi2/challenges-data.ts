const n = (x: number) => new Intl.NumberFormat("el-GR", { maximumFractionDigits: 3 }).format(x);
const step = (
  id: string, question: string, law: string, formula: string, hint: string,
  explanation: string, answer: number, unit: string,
): SolutionStep => ({ id, question, law, formula, hint, explanation, answer, unit });

export function solveChallenge(family: ChallengeFamily, variant: ChallengeVariant): SolvedChallenge {
  const p = variant.p;
  const common = { phases: family.phases, target: family.keyIdea, hasEnergyLoss: true };
  switch (family.id) {
    case "stick-friction": {
      const V = Math.sqrt(2 * p.mu * p.g * p.s);
      const u = (p.M + p.m) * V / p.m;
      const Q = 0.5 * p.m * u * u - 0.5 * (p.M + p.m) * V * V;
      return {
        ...common,
        prompt: "Βλήμα μάζας " + n(1000*p.m) + " g σφηνώνεται οριζόντια σε ακίνητο ξύλο μάζας " + n(p.M) +
          " kg πάνω σε τραχύ οριζόντιο επίπεδο (μ=" + n(p.mu) + "). Το συσσωμάτωμα σταματά αφού διανύσει " +
          n(p.s) + " m. Δίνεται g=" + n(p.g) + " m/s². Βρες την κοινή ταχύτητα μετά την κρούση, την αρχική ταχύτητα του βλήματος και την απώλεια ενέργειας μόνο στην κρούση.",
        steps: [
          step("V", "Πόση είναι η κοινή ταχύτητα V αμέσως μετά την κρούση;", "ΘΜΚΕ στην ολίσθηση", "V = √(2μgs)", "Ξεκίνα από το διάστημα ακινητοποίησης· η τριβή καταναλώνει την κινητική.", "Η τριβή δρα μετά την κρούση: ½(M+m)V² = μ(M+m)gs.", V, "m/s"),
          step("u", "Ποια ήταν η ταχύτητα u του βλήματος πριν από την κρούση;", "ΑΔΟ μόνο στην κρούση", "u = (M+m)V/m", "Το ξύλο ήταν ακίνητο. Τώρα ξέρεις την V του συσσωματώματος.", "m·u = (M+m)V, αφού η εξωτερική οριζόντια ώθηση είναι αμελητέα στην κρούση.", u, "m/s"),
          step("Q", "Πόση κινητική ενέργεια χάθηκε κατά την κρούση;", "Διαφορά κινητικών ενεργειών", "Q = ½mu² − ½(M+m)V²", "Μην προσθέσεις την ενέργεια που χάνεται αργότερα στην ολίσθηση.", "Σύγκρινε τις κινητικές ακριβώς πριν και ακριβώς μετά την πλαστική κρούση.", Q, "J"),
        ],
      };
    }
    case "ballistic": {
      const V = Math.sqrt(2 * p.g * p.h);
      const u = (p.M + p.m) * V / p.m;
      const loss = 100 * (1 - p.m / (p.M + p.m));
      return {
        ...common,
        prompt: "Οριζόντιο βλήμα μάζας " + n(1000*p.m) + " g σφηνώνεται σε ακίνητο ξύλο μάζας " + n(p.M) +
          " kg, που κρέμεται από νήμα. Μετά την κρούση ανεβαίνουν μαζί κατά " + n(p.h) + " m. Αγνόησε αντιστάσεις (g=" +
          n(p.g) + " m/s²). Υπολόγισε την ταχύτητα αμέσως μετά την κρούση, την ταχύτητα του βλήματος πριν και το ποσοστό απώλειας κινητικής ενέργειας στην κρούση.",
        steps: [
          step("V", "Πόσο είναι το μέτρο V της κοινής ταχύτητας μετά την κρούση;", "ΑΔΜΕ στην άνοδο", "V = √(2gh)", "Η άνοδος είναι χωρίς απώλειες· η ταχύτητα στο μέγιστο ύψος μηδενίζεται.", "½(M+m)V²=(M+m)gh. Η μάζα απλοποιείται.", V, "m/s"),
          step("u", "Πόσο ήταν το μέτρο u της αρχικής ταχύτητας του βλήματος;", "ΑΔΟ στον οριζόντιο άξονα", "u = (M+m)V/m", "Στην κρούση η οριζόντια εξωτερική ώθηση θεωρείται αμελητέα.", "m·u=(M+m)V. Δεν χρησιμοποιούμε ΑΔΜΕ σε όλη την κρούση.", u, "m/s"),
          step("loss", "Τι ποσοστό (%) της αρχικής κινητικής χάθηκε στην κρούση;", "Κινητικές πριν και μετά", "Π% = [1 − m/(M+m)]·100", "Γράψε Kπριν=½mu² και Kμετά=½(M+m)V².", "Από ΑΔΟ, V=mu/(M+m), οπότε Kμετά/Kπριν=m/(M+m).", loss, "%"),
        ],
      };
    }
    case "pass-edge": {
      const t = Math.sqrt(2 * p.H / p.g);
      const V = p.x / t;
      const uOut = (p.m * p.u - p.M * V) / p.m;
      const Q = 0.5 * p.m * (p.u*p.u - uOut*uOut) - 0.5 * p.M * V*V;
      return {
        ...common,
        prompt: "Βλήμα " + n(1000*p.m) + " g με ταχύτητα " + n(p.u) + " m/s διαπερνά κύβο " +
          n(p.M) + " kg ακίνητο στην άκρη λείου οριζόντιου τραπεζιού ύψους " + n(p.H) +
          " m. Ο κύβος φεύγει οριζόντια και προσγειώνεται σε οριζόντια απόσταση " + n(p.x) +
          " m. Το βλήμα εξέρχεται προς την αρχική του κατεύθυνση. g=" + n(p.g) +
          " m/s². Βρες χρόνο πτήσης, ταχύτητα κύβου, ταχύτητα εξόδου βλήματος και απώλεια κινητικής ενέργειας στην κρούση.",
        steps: [
          step("t", "Ποιος είναι ο χρόνος t πτώσης του κύβου;", "Οριζόντια βολή — κατακόρυφος άξονας", "t = √(2H/g)", "Η κατακόρυφη αρχική ταχύτητα είναι μηδέν.", "Η κατακόρυφη κίνηση είναι ελεύθερη πτώση: H=½gt².", t, "s"),
          step("V", "Ποια η οριζόντια ταχύτητα V του κύβου αμέσως μετά την κρούση;", "Οριζόντια βολή — οριζόντιος άξονας", "V = x/t", "Η οριζόντια ταχύτητα είναι σταθερή στην πτήση.", "x=Vt χωρίς οριζόντια επιτάχυνση.", V, "m/s"),
          step("uout", "Πόση είναι η ταχύτητα εξόδου του βλήματος;", "ΑΔΟ στη σύντομη διάτρηση", "u_έξ = (mu_αρχ − MV)/m", "Μετά την κρούση κινούνται δύο σώματα, με δύο διαφορετικές ταχύτητες.", "m·u_αρχ=m·u_έξ+M·V, θεωρώντας αμελητέα εξωτερική οριζόντια ώθηση.", uOut, "m/s"),
          step("Q", "Πόσα J κινητικής ενέργειας χάθηκαν μόνο στην κρούση;", "Διαφορά κινητικών", "Q = ½mu² − ½m·u_έξ² − ½MV²", "Μη συγκρίνεις με τη μετέπειτα πτώση του κύβου.", "Στη διάτρηση μετρούν και η κινητική του βλήματος και η κινητική του κύβου.", Q, "J"),
        ],
      };
    }
    case "elastic-ramp": {
      const v1 = (p.m1 - p.m2) / (p.m1+p.m2) * p.u;
      const v2 = 2 * p.m1 / (p.m1+p.m2) * p.u;
      const h = v2*v2/(2*p.g);
      return {
        ...common, hasEnergyLoss: false,
        prompt: "Σφαίρα " + n(p.m1) + " kg κινείται δεξιά με " + n(p.u) + " m/s και συγκρούεται ελαστικά, μετωπικά με ακίνητη σφαίρα " +
          n(p.m2) + " kg σε λείο οριζόντιο δάπεδο. Έπειτα η δεύτερη ανεβαίνει σε λεία ράμπα. Δεξιά θετική φορά, g=" +
          n(p.g) + " m/s². Βρες και τις δύο προσημασμένες ταχύτητες μετά την κρούση και το μέγιστο ύψος.",
        steps: [
          step("v1", "Ποια η προσημασμένη τελική ταχύτητα της πρώτης σφαίρας;", "ΑΔΟ + διατήρηση Κ στην ελαστική", "v₁′ = (m₁−m₂)u/(m₁+m₂)", "Πρόσεξε μήπως γυρίζει πίσω: το πρόσημο είναι σημαντικό.", "Η κρούση είναι ελαστική: λύσε ΑΔΟ και Kπριν=Kμετά.", v1, "m/s"),
          step("v2", "Ποια η προσημασμένη τελική ταχύτητα της δεύτερης σφαίρας;", "ΑΔΟ + διατήρηση Κ στην ελαστική", "v₂′ = 2m₁u/(m₁+m₂)", "Η δεύτερη αρχικά ήταν ακίνητη.", "Χρησιμοποίησε τον τύπο μετωπικής ελαστικής για ακίνητο δεύτερο σώμα.", v2, "m/s"),
          step("h", "Σε τι ύψος h ανεβαίνει η δεύτερη σφαίρα;", "ΑΔΜΕ στη λεία ράμπα", "h = v₂′²/(2g)", "Στο μέγιστο ύψος μηδενίζεται στιγμιαία η ταχύτητα.", "½m₂v₂′²=m₂gh, χωρίς απώλειες μετά την κρούση.", h, "m"),
        ],
      };
    }
    case "friction-collision-flight": {
      const before = Math.sqrt(p.u*p.u - 2*p.mu*p.g*p.d);
      const V = p.m * before / (p.m+p.M);
      const t = Math.sqrt(2*p.H/p.g);
      const x = V*t;
      return {
        ...common,
        prompt: "Σώμα " + n(p.m) + " kg κινείται με " + n(p.u) + " m/s σε τραχύ οριζόντιο δάπεδο (μ=" +
          n(p.mu) + ") για " + n(p.d) + " m. Στο τέλος συγκρούεται πλαστικά με ακίνητο κύβο " + n(p.M) +
          " kg στην άκρη τραπεζιού. Το συσσωμάτωμα εγκαταλείπει οριζόντια το τραπέζι ύψους " + n(p.H) +
          " m. g=" + n(p.g) + " m/s². Βρες ταχύτητα αμέσως πριν την κρούση, κοινή ταχύτητα και οριζόντιο βεληνεκές.",
        steps: [
          step("before", "Πόση η ταχύτητα του σώματος αμέσως πριν από την κρούση;", "ΘΜΚΕ στην αρχική ολίσθηση", "v = √(u₀²−2μgd)", "Η τριβή αφαιρεί κινητική ενέργεια πριν την κρούση.", "½mv²−½mu₀²=−μmgd.", before, "m/s"),
          step("V", "Πόσο είναι το μέτρο V της κοινής ταχύτητας μετά την κρούση;", "ΑΔΟ στην πλαστική κρούση", "V = mv/(m+M)", "Χρησιμοποίησε την ταχύτητα ΠΡΙΝ την κρούση, όχι την αρχική.", "m·v=(m+M)V στη σύντομη κρούση.", V, "m/s"),
          step("x", "Ποιο είναι το οριζόντιο βεληνεκές x του συσσωματώματος;", "Οριζόντια βολή", "x = V√(2H/g)", "Η κατακόρυφη πτώση δίνει τον χρόνο. Μετά x=Vt.", "t=√(2H/g), ενώ οριζόντια δεν υπάρχει επιτάχυνση.", x, "m"),
        ],
      };
    }
    case "bounce-force": {
      const down = Math.sqrt(2*p.g*p.h1);
      const up = Math.sqrt(2*p.g*p.h2);
      const F = p.m*(down+up)/p.dt + p.m*p.g;
      return {
        ...common,
        prompt: "Μπάλα " + n(p.m) + " kg αφήνεται από ύψος " + n(p.h1) + " m πάνω από οριζόντιο δάπεδο. Η επαφή διαρκεί " +
          n(p.dt) + " s και η μπάλα αναπηδά μέχρι ύψος " + n(p.h2) + " m. g=" + n(p.g) +
          " m/s², αμελητέα αντίσταση αέρα. Βρες τα μέτρα των ταχυτήτων πριν και μετά, και τη μέση δύναμη του δαπέδου.",
        steps: [
          step("down", "Πόσο το μέτρο της ταχύτητας λίγο πριν από την επαφή;", "ΑΔΜΕ στην πτώση", "v↓ = √(2gh₁)", "Η μπάλα αφήνεται από ηρεμία.", "mgh₁=½mv↓².", down, "m/s"),
          step("up", "Πόσο το μέτρο της ταχύτητας αμέσως μετά την επαφή;", "ΑΔΜΕ στην άνοδο", "v↑ = √(2gh₂)", "Δούλεψε ανάστροφα από το μέγιστο ύψος της αναπήδησης.", "½mv↑²=mgh₂.", up, "m/s"),
          step("F", "Πόση είναι η μέση κάθετη δύναμη του εδάφους;", "Ώθηση — συνισταμένη", "Nμ = m(v↑+v↓)/Δt + mg", "Προς τα πάνω θετική: pπριν=−mv↓, pμετά=+mv↑.", "(Nμ−mg)Δt=m(v↑+v↓). Το βάρος δρα και κατά την επαφή.", F, "N"),
        ],
      };
    }
    case "spring-explosion": {
      const v2 = Math.sqrt(2*p.E*p.m1/(p.m2*(p.m1+p.m2)));
      const v1 = -p.m2*v2/p.m1;
      const V = p.m2*v2/(p.m2+p.m3);
      const Q = 0.5*p.m2*v2*v2 - 0.5*(p.m2+p.m3)*V*V;
      return {
        ...common,
        prompt: "Δύο αμαξίδια " + n(p.m1) + " kg και " + n(p.m2) +
          " kg είναι ακίνητα σε λείο οριζόντιο δάπεδο, με συμπιεσμένο ιδανικό ελατήριο ανάμεσά τους. Το ελατήριο δίνει συνολική κινητική ενέργεια " +
          n(p.E) + " J και τα αμαξίδια αποχωρίζονται. Θετική φορά: η κίνηση του δεύτερου προς τα δεξιά. Το δεύτερο αμαξίδιο αργότερα συγκρούεται πλαστικά με ακίνητο σώμα " +
          n(p.m3) + " kg. Βρες τις προσημασμένες ταχύτητες των δύο αμαξιδίων μετά την εκτόνωση, την κοινή ταχύτητα μετά τη δεύτερη κρούση και την απώλεια κινητικής στη δεύτερη κρούση.",
        steps: [
          step("v2", "Ποια η ταχύτητα του δεύτερου αμαξιδίου μετά την εκτόνωση;", "ΑΔΟ + ενέργεια ελατηρίου", "v₂ = √[2Em₁/(m₂(m₁+m₂))]", "Αρχικά η συνολική ορμή είναι μηδέν και η κινητική είναι E.", "m₁v₁+m₂v₂=0, ½m₁v₁²+½m₂v₂²=E. Λύνουμε το σύστημα.", v2, "m/s"),
          step("v1", "Ποια η προσημασμένη ταχύτητα του πρώτου αμαξιδίου;", "ΑΔΟ στην εκτόνωση", "v₁ = −m₂v₂/m₁", "Το πρώτο κινείται αντίθετα από το δεύτερο.", "Αφού η αρχική ορμή είναι μηδέν, m₁v₁=−m₂v₂.", v1, "m/s"),
          step("V", "Πόσο η κοινή ταχύτητα μετά τη δεύτερη κρούση;", "Νέα ΑΔΟ σε νέο σύστημα", "V = m₂v₂/(m₂+m₃)", "Τώρα το σύστημα είναι δεύτερο αμαξίδιο + ακίνητος κύβος.", "m₂v₂=(m₂+m₃)V στη σύντομη πλαστική κρούση.", V, "m/s"),
          step("Q", "Πόση κινητική ενέργεια χάθηκε στη δεύτερη κρούση;", "Διαφορά κινητικών δεύτερης κρούσης", "Q = ½m₂v₂²−½(m₂+m₃)V²", "Η E του ελατηρίου δεν είναι η απώλεια της δεύτερης κρούσης.", "Υπολόγισε κινητικές πριν και μετά ΜΟΝΟ τη δεύτερη κρούση.", Q, "J"),
        ],
      };
    }
    case "pendulum-elastic-spring": {
      const u = Math.sqrt(2*p.g*p.h);
      const v1 = (p.m1-p.m2)*u/(p.m1+p.m2);
      const v2 = 2*p.m1*u/(p.m1+p.m2);
      const x = Math.sqrt(p.m2*v2*v2/p.k);
      return {
        ...common, hasEnergyLoss: false,
        prompt: "Σφαίρα " + n(p.m1) + " kg δεμένη σε νήμα αφήνεται από ύψος " + n(p.h) +
          " m πάνω από την κατώτατη θέση. Εκεί χτυπά μετωπικά και ελαστικά ακίνητο κύβο " + n(p.m2) +
          " kg πάνω σε λείο οριζόντιο δάπεδο. Ο κύβος κατόπιν συμπιέζει ιδανικό ελατήριο σταθεράς k=" +
          n(p.k) + " N/m. g=" + n(p.g) +
          " m/s². Θετική φορά της αρχικής κίνησης. Βρες ταχύτητα πριν την κρούση, προσημασμένη ταχύτητα της σφαίρας μετά, ταχύτητα κύβου μετά και μέγιστη συμπίεση.",
        steps: [
          step("u", "Με τι ταχύτητα φτάνει η σφαίρα στο κατώτατο σημείο;", "ΑΔΜΕ στην κάθοδο", "u = √(2gh)", "Η δυναμική ενέργεια της σφαίρας μετατρέπεται σε κινητική.", "m₁gh=½m₁u².", u, "m/s"),
          step("v1", "Ποια η προσημασμένη ταχύτητα της σφαίρας μετά την κρούση;", "Ελαστική: ΑΔΟ + διατήρηση Κ", "v₁′ = (m₁−m₂)u/(m₁+m₂)", "Αν m₁<m₂, αναμένεις αρνητικό πρόσημο.", "Από τις δύο εξισώσεις διατήρησης κατά την ελαστική μετωπική κρούση.", v1, "m/s"),
          step("v2", "Με τι ταχύτητα κινείται ο κύβος μετά την κρούση;", "Ελαστική: ΑΔΟ + διατήρηση Κ", "v₂′ = 2m₁u/(m₁+m₂)", "Ο κύβος αρχικά ακίνητος.", "Η ταχύτητα προκύπτει από τις εξισώσεις της ελαστικής κρούσης.", v2, "m/s"),
          step("x", "Ποια η μέγιστη συμπίεση x του ελατηρίου;", "ΑΔΜΕ κύβου–ελατηρίου", "x = √(m₂v₂′²/k)", "Στη μέγιστη συμπίεση η ταχύτητα μηδενίζεται στιγμιαία.", "½m₂v₂′²=½kx² χωρίς τριβές.", x, "m"),
        ],
      };
    }
  }
}

export function answerMatches(input: string, expected: number): boolean {
  const value = Number(input.trim().replace(",", "."));
  return input.trim().length > 0 && Number.isFinite(value) &&
    Math.abs(value - expected) <= Math.max(0.015, Math.abs(expected) * 0.005);
}

export function formatAnswer(value: number): string {
  return n(value);
}
