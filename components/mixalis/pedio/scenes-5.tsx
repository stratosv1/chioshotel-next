  n: 25,
  title: "Ηλεκτρόνιο επιταχύνεται",
  what: "Ένα ηλεκτρόνιο ξεκινά ακίνητο από την αρνητική πλάκα και επιταχύνεται προς τη θετική. Η κινητική ενέργεια που κερδίζει εξαρτάται μόνο από την τάση: e·V.",
