function QuizItem({ item, n, color }: { item: Quiz; n: number; color: string }) {
  const [picked, setPicked] = useState<number | null>(null);
  const done = picked !== null;
  return (
    <li className="border-t border-[#ddd5c7] pt-3">
      <p className="text-[15px] leading-7 text-[#2c2825]">
        <span className="font-semibold" style={{ color }}>
          {n}.{" "}
        </span>
        {rich(item.q)}
      </p>
      <div className="mt-2 flex flex-wrap gap-2">
        {item.options.map((o, i) => {
          const isRight = i === item.correct;
          const style = !done
            ? "border-[#ddd5c7] bg-white text-[#2c2825] hover:bg-[#f3efe8]"
            : isRight
              ? "border-[#1f9d55] bg-[#ecf7f0] text-[#14532d]"
              : i === picked
                ? "border-[#c0392b] bg-[#fdeeec] text-[#7a2c22]"
                : "border-[#ddd5c7] bg-white text-[#9aa3b2]";
          return (
            <button
              key={o}
              type="button"
              disabled={done}
              onClick={() => setPicked(i)}
              className={`rounded-xl border px-3 py-1.5 text-left text-sm font-medium ${style}`}
            >
              {rich(o)}
              {done && isRight ? " ✓" : done && i === picked ? " ✗" : ""}
            </button>
          );
        })}
      </div>
      {done ? (
        <p className="mt-2 text-sm leading-6 text-[#3d4452]">
          <span className={`font-semibold ${picked === item.correct ? "text-[#1f9d55]" : "text-[#c0392b]"}`}>
            {picked === item.correct ? "Σωστά. " : "Όχι ακριβώς. "}
          </span>
          {rich(item.why)}{" "}
          <button type="button" onClick={() => setPicked(null)} className="font-semibold text-[#857261] underline underline-offset-2">
            Ξανά
          </button>
        </p>
      ) : null}
    </li>
  );
}

export function QuickCheck({ items, color }: { items: Quiz[]; color: string }) {
  return (
    <div className="mt-12 max-w-4xl">
      <p className="text-xs font-semibold uppercase tracking-[0.18em]" style={{ color }}>
        Γρήγορος έλεγχος
      </p>
      <p className="mt-1 text-[15px] leading-7 text-[#5c534c]">Ερωτήσεις σαν το Θέμα Α. Διάλεξε απάντηση και μετά διάβασε το «γιατί».</p>
      <ol className="mt-3 space-y-3">
        {items.map((it, i) => (
          <QuizItem key={it.q} item={it} n={i + 1} color={color} />
        ))}
      </ol>
    </div>
  );
}
